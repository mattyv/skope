#!/usr/bin/env node
// Generates src/embedded.gen.ts: files that ship inside every build, the
// standalone binary included, so skope can write them out without the repo.
//   - SKILLS, the agent skills in skills/ (write-skope-skill and
//     run-skope-skill), for `skope --install-skill`
//   - DEMO, the disk-full skill with its tests and fakes, for `skope --demo`
// tests/host/embedded.test.ts fails if the committed file is stale.
//
//   node scripts/gen-embedded.mjs        write src/embedded.gen.ts

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "embedded.gen.ts");
const read = (p) => readFileSync(join(ROOT, p), "utf8");

export function generate() {
  const skills = Object.fromEntries(["write-skope-skill", "run-skope-skill"].map((name) => [name, read(`skills/${name}/SKILL.md`)]));
  const demo = {
    "SKILL.md": read("fixtures/disk-full/SKILL.md"),
    "tests.yaml": read("fixtures/disk-full/demo/tests.yaml"),
    "answers.yaml": read("fixtures/disk-full/demo/answers.yaml"),
    "commands.yaml": read("fixtures/disk-full/demo/commands.yaml"),
  };
  return [
    "// Generated by scripts/gen-embedded.mjs from skills/ and fixtures/disk-full/. Don't edit.",
    `export const SKILLS: Record<string, string> = ${JSON.stringify(skills, null, 2)};`,
    `export const DEMO: Record<string, string> = ${JSON.stringify(demo, null, 2)};`,
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) writeFileSync(OUT, generate());
